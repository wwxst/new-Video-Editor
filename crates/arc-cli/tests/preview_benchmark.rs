//! Phase C preview benchmark (docs/specs/phase-c-plan.md C3): 1080p canvas, 4 video tracks, 8
//! effects, measured through the preview pipeline. The numbers are printed and recorded in
//! reports/phase-c-c3-2026-11-26.md; this test only asserts that the pipeline works at a sane rate,
//! so a slow CI software adapter never blocks the suite.

use arc_cli::preview::{PreviewEngine, PreviewQuality};
use arc_core::engine::{ApplyRequest, Engine};
use arc_core::model::{Project, Resolution};
use arc_core::time::FrameRate;
use arc_core::Command;
use serde_json::json;
use std::path::Path;
use std::sync::{Mutex, MutexGuard};
use std::time::Instant;

static GPU_SERIAL: Mutex<()> = Mutex::new(());

fn serial() -> MutexGuard<'static, ()> {
    GPU_SERIAL.lock().unwrap_or_else(|poisoned| poisoned.into_inner())
}

/// 1920x1080, 1 s (30 frames) FFV1 source generated by the pinned ffmpeg.
fn fixture(dir: &Path) -> std::path::PathBuf {
    let path = dir.join("bench1080.mkv");
    let out = std::process::Command::new(arc_media::tools::ffmpeg())
        .args([
            "-hide_banner",
            "-v",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "testsrc2=size=1920x1080:rate=30:duration=1",
            "-c:v",
            "ffv1",
        ])
        .arg(&path)
        .output()
        .expect("run ffmpeg");
    assert!(
        out.status.success(),
        "fixture: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    path
}

/// 4 video tracks x 1 clip (2 s? 1 s) x 2 effects = 8 effect instances at 1080p.
fn bench_project(dir: &Path) -> Project {
    let media = fixture(dir);
    let mut engine = Engine::new(
        Project::new("Bench", FrameRate::Fps30, Resolution { w: 1920, h: 1080 }),
        0,
        arc_render::builtin::catalog(),
    )
    .expect("engine");
    let mut commands: Vec<serde_json::Value> = vec![
        json!({"op":"asset.import","id":"as_a","path":media.to_str().expect("utf8"),"kind":"video","probe":{"duration":{"num":1,"den":1}}}),
    ];
    for track in 1..=4 {
        commands.push(json!({"op":"track.add","id":format!("tr_v{track}"),"kind":"video"}));
        commands.push(json!({"op":"timeline.add_clip","id":format!("cl_{track}"),"track":format!("tr_v{track}"),"asset":"as_a","start":{"num":0,"den":1},"duration":{"num":1,"den":1}}));
        commands.push(json!({"op":"effect.add","clip":format!("cl_{track}"),"effect":"core.color.correct"}));
        commands.push(json!({"op":"effect.add","clip":format!("cl_{track}"),"effect":"core.stylize.vignette"}));
    }
    let commands: Vec<Command> = commands
        .into_iter()
        .map(|v| serde_json::from_value(v).expect("command"))
        .collect();
    engine
        .apply(ApplyRequest {
            commands,
            ..Default::default()
        })
        .expect("apply");
    (*engine.snapshot()).clone()
}

fn measure(engine: &mut PreviewEngine, quality: PreviewQuality, frames: i64) -> (f64, f64) {
    engine.set_quality(quality);
    for f in 0..2 {
        engine.frame(f).expect("warm-up");
    }
    let started = Instant::now();
    for f in 0..frames {
        engine.frame(f).expect("bench frame");
    }
    let elapsed = started.elapsed().as_secs_f64();
    (frames as f64 / elapsed, elapsed * 1000.0 / frames as f64)
}

/// Prints the C3 benchmark data point: 1080p, 4 tracks, 8 effects, full and half quality.
#[test]
fn preview_benchmark_1080p_4_tracks_8_effects() {
    let _serial = serial();
    let dir = tempfile::tempdir().expect("tmp");
    let project = bench_project(dir.path());
    let mut engine = PreviewEngine::new(project, dir.path().to_path_buf(), PreviewQuality::Full)
        .expect("preview engine");
    let frames = 20;
    let (full_fps, full_ms) = measure(&mut engine, PreviewQuality::Full, frames);
    let (half_fps, half_ms) = measure(&mut engine, PreviewQuality::Half, frames);
    eprintln!(
        "C3 benchmark: adapter={} canvas=1920x1080 tracks=4 effects=8 frames={frames} full={full_fps:.2} fps ({full_ms:.2} ms/frame) half={half_fps:.2} fps ({half_ms:.2} ms/frame)",
        engine.adapter_info()
    );
    assert!(full_fps > 0.5, "the pipeline must at least run: {full_fps} fps");
    assert!(half_fps > 0.5, "half quality must run: {half_fps} fps");
    // The half-quality path composes a quarter of the pixels; it must not be slower.
    assert!(
        half_fps >= full_fps * 0.8,
        "half quality should not be slower than full: {half_fps} vs {full_fps}"
    );
}
